namespace Fanex.CRM.Feedback.Controllers
{
    using System;
    using System.Collections.Generic;
    using System.Linq;
    using System.Threading.Tasks;
    using System.Web.Mvc;
    using Common.Models;
    using Common.Services;
    using Fanex.CRM.Common.Constants;
    using Fanex.CRM.Common.Controllers;
    using Fanex.CRM.Common.Excel;
    using Fanex.CRM.Feedback.Criteria;
    using Fanex.CRM.Feedback.Excels;
    using Fanex.CRM.Feedback.Excels.LatestFeedback;
    using Fanex.CRM.Feedback.Models;
    using Fanex.CRM.Feedback.Resources;
    using Fanex.CRM.Feedback.Services;
    using Fanex.CRM.Feedback.Services.TicketRef;
    using Fanex.CRM.Feedback.ViewModels;
    using Fanex.Logging;
    using Fanex.NAP.Core.Business;
    using Fanex.NAP.Core.Web.Attribute;
    using Newtonsoft.Json;
    using Setting.Services;

    public class FeedbacksController : ReadOnlyBaseController
    {
        private readonly IFeedbackService _feedbackService;
        private readonly ISettingService _serviceSetting;
        private readonly ITicketRefService _ticketRefService;
        private const string autoGenerated = "<span style=\"color: rgb(255, 0, 0);\">This is an auto-generated entry.</span>";


        public FeedbacksController()
            : this(null, null, null)
        {
        }

        public FeedbacksController(IFeedbackService feedbackService, ISettingService serviceSetting, ITicketRefService ticketRefService)
        {
            _feedbackService = feedbackService ?? new FeedbackService();
            _serviceSetting = serviceSetting ?? new SettingService();
            _ticketRefService = ticketRefService ?? new TicketRefService();
        }

        [HttpGet]
        public ActionResult AllSetting()
        {
            var hasPermission = HasReadPermission(FunctionPermissions.CreateUpdateFeedbackAndCustomerInfo) ||
                                HasReadPermission(FunctionPermissions.DeleteFeedback);
            dynamic settings = null;
            if (hasPermission)
            {
                settings = _feedbackService.GetAllSettings();
            }

            return Json(settings, JsonRequestBehavior.AllowGet);
        }

        [HttpGet]
        public ActionResult AllSettingDeleteFeedback()
        {
            var hasPermission = HasReadPermission(FunctionPermissions.CreateUpdateFeedbackAndCustomerInfo) ||
                                HasReadPermission(FunctionPermissions.DeleteFeedback);
            dynamic settings = null;
            if (hasPermission)
            {
                settings = _feedbackService.GetAllSettingsDeleteFb();
            }

            return Json(settings, JsonRequestBehavior.AllowGet);
        }

        [HttpGet]
        [NapAuth(FunctionKey = FunctionPermissions.CreateUpdateFeedbackAndCustomerInfo, Policy = Constant.Policy.Read)]
        public ActionResult ManageFeedback(ManageFeedbackViewModel model)
        {
            return Redirect(string.Format("{0}/ManageFeedback", ExternalDomain));
        }
        
        [HttpGet]
        [NapAuth(FunctionKey = FunctionPermissions.CreateUpdateFeedbackAndCustomerInfo, Policy = Constant.Policy.Read)]
        public ActionResult LatestFeedback(int custId = 0, string custName = null)
        {
            return Redirect(string.Format("{0}/LatestFeedback", ExternalDomain));
        }


        [HttpGet]
        [NapAuth(FunctionKey = FunctionPermissions.DeleteFeedback, Policy = Constant.Policy.Read)]
        public ActionResult DeletedFeedback()
        {
            return Redirect(string.Format("{0}/DeletedFeedback", ExternalDomain));
        }
        

        [HttpGet]
        [NapAuth(FunctionKey = FunctionPermissions.CreateUpdateFeedbackAndCustomerInfo, Policy = Constant.Policy.Read)]
        public ActionResult CreateMultipleLogs()
        {
            return Redirect(string.Format("{0}/MultipleLogs", ExternalDomain));
        }


        [HttpPost]
        public ActionResult CheckFeedbackDuplication(CheckFeedbackDuplicationCriteria criteria)
        {
            try
            {
                var result = _feedbackService.CheckFeedbackDuplication(criteria);
                return Json(result, JsonRequestBehavior.AllowGet);
            }
            catch
            {
                LogService.Error("CheckFeedbackDuplication Error: " + JsonConvert.SerializeObject(criteria));
                throw;
            }
        }

        [HttpPost]
        public async Task<ActionResult> GetTicketInfoByRefNoAsync(long Refno)
        {
            try
            {
                if(Refno == 0)
                {
                    Json(new TicketInfo() , JsonRequestBehavior.AllowGet);
                }
                var tickets = await _ticketRefService.GetTicketByRefNoAsync(Refno);
                if (tickets.ErrorCode == "0")
                {
                    tickets.Description = autoGenerated + "<br /><br />" + tickets.Description;
                }
                return Json(tickets, JsonRequestBehavior.AllowGet);
            }
            catch(Exception exception)
            {
                LoggingHelper.Error(exception, Refno);
                throw;
            }
        }

        public string GetBalanceUpday()
        {
            var balanceDay = _ticketRefService.GetBalanceUpday();
            var balanceDayFormat = balanceDay.ToString("MM/dd/yyyy");
            return balanceDayFormat;
        }
    }
}