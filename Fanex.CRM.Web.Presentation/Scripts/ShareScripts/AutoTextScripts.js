var autoTextScripts;
var AutoTextScripts = function () {
    var self = this;

    //  Generate Text Preview
    self.generateTextPreview = function (autoGeneratedText, trustAsHtmlFunc) {
        var previewText = autoGeneratedText.replace(/\n/g, "<br>");
        if (previewText && previewText != "<br>") {
            previewText = previewText + "<br><br>";
        }
        return trustAsHtmlFunc(previewText);
    };

    // Update Customer Prefix
    self.updatePrefixForCusomter = function (hasRelated, relatedCustomers, autoGeneratedText, trustAsHtmlFunc) {
        var customerPrefix = self.generateCustomerPrefix(hasRelated, relatedCustomers);
        autoGeneratedText = (autoGeneratedText.indexOf("System ID:") >= 0) ?
            autoGeneratedText.replace(/System ID:.*/, customerPrefix) :
            autoGeneratedText + "\n" + customerPrefix;

        return {
            autoGeneratedText: autoGeneratedText,
            previewText: trustAsHtmlFunc ? self.generateTextPreview(autoGeneratedText, trustAsHtmlFunc) : ''
        };
    };

    self.generateCustomerPrefix = function (hasRelated, relatedCustomers) {
        var customerArr = [];
        if (hasRelated) {
            angular.forEach(relatedCustomers, function (customer, index) {
                if (customer.Id != 0) {
                    customerArr.push(customer.Name);
                }
            });
        }

        return "System ID: " + customerArr.join(", ");
    };

    // Update TimeAndTool Prefix
    self.updatePrefixForTimeAndTool = function (
        startTime,
        autoGeneratedText,
        stringFormatFunc,
        remarkPrefix,
        latestedSelectedCommunication,
        communicationTools,
        trustAsHtmlFunc) {
        var newTimeAndToolPrefix = self.generateTimeAndToolPrefix(
            stringFormatFunc,
            startTime,
            remarkPrefix,
            latestedSelectedCommunication);
        var oldTimeAndToolPrefix = self.matchTimeAndToolPrefix(communicationTools, autoGeneratedText);
        autoGeneratedText = (oldTimeAndToolPrefix != '') ?
            autoGeneratedText.replace(oldTimeAndToolPrefix, newTimeAndToolPrefix) :
            newTimeAndToolPrefix + "\n" + autoGeneratedText;

        return {
            autoGeneratedText: autoGeneratedText,
            previewText: trustAsHtmlFunc ? self.generateTextPreview(autoGeneratedText, trustAsHtmlFunc) : ''
        };
    };

    self.generateTimeAndToolPrefix = function (stringFormatFunc, startTime, remarkPrefix, latestedSelectedCommunication) {
        return stringFormatFunc("Date Time & Tool: {0}/{1}",
            [moment(startTime).format(remarkPrefix), latestedSelectedCommunication]);
    };

    self.matchTimeAndToolPrefix = function (communicationTools, autoGeneratedText) {
        communicationTools.push({ Name: "N/A" });
        var pattern = "Date Time & Tool: \\d{8}\\/\\d{2}:\\d{2}\\D{2}\\/";
        for (var i = 0; i < communicationTools.length; i++) {
            var tool = communicationTools[i];
            var match = autoGeneratedText.match(new RegExp(pattern + tool.Name));
            if (match != null) {
                return match[0];
            }
        }

        return '';
    };

    // Update subject based on selected Categories
    self.updateSubjectOnSelectedCategories = function (selectedCategories, subject) {
        var updatedSubject = subject;

        if (selectedCategories.length == 0 && subject != '') {
            updatedSubject = '';
        }
        else if (selectedCategories.length == 1) {
            updatedSubject = selectedCategories[0].Name;
        }

        return updatedSubject;
    };
};

autoTextScripts = new AutoTextScripts();