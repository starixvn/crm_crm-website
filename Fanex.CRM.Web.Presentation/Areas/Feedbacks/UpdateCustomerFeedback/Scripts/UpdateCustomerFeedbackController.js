(function () {
    "use strict";
    /* global crmConstants,
    sharedScriptManager,
    SettingManager,
    hotKeyManager,
    updateFeedbackResources,
    feedbackId,
    hasReviewFeedbackPermission,
    isShowDeletedStatus,
    isDeletedFeedbackView,
    orgLengt:true */
    /* jshint camelcase: false */
    angular.module('feedbacks-updatecustomerfeedback-application').controller('updateCustomerFeedbackController',
        ['$scope', 'UpdateCustomerFeedbackService', '$uiBlockerService', 'alertBoxService', '$sce',
            function ($scope, feedbackService, $uiBlockerService, alertBoxService, $sce) {
                $scope.feedback = null;
                $scope.reviewedBy = '';
                $scope.hasReviewPermission = hasReviewFeedbackPermission === 'True';
                $scope.bettypes = null;
                $scope.subProducts = null;
                $scope.customersInput = '';
                $scope.TextSettings = {
                    Filter: "Search",
                    NoItemChecked: "N/A",
                    CheckAll: "All"
                };
                $scope.selectedSubProductIds = [];
                $scope.selectedBettypeIds = [];
                $scope.selectedSubCategoryIds = [];

                var oldReview;
                $scope.panelManager = {
                    customer: false,
                    detail: true,
                    description: true,
                    solution: true,
                    review: false,
                    showDescriptionPreview: true,
                    showSolutionPreview: true,
                    showReviewPreview: true
                };
                $scope.requiredManager = {
                    subject: true,
                    description: true,
                    solution: true,
                    review: true
                };
                $scope.autoGeneratedText = '';
                $scope.CustomerCheckboxChanged = false;

                // Subject with auto-complete.
                $scope.feedbackSubjectTemplateList = [];
                $scope.feedbackSubjectTemplateTotalPage = 0;
                $scope.isLoadedFeedbackSubjectTemplate = false;

                // Subject functions.
                $scope.updateSelectedSubject = function (subject) {
                    $scope.feedback.Subject = subject;
                };
                $scope.getNumberOfFeedbackSubjectTemplate = function () {
                    feedbackService.getNumberOfFeedbackSubjectTemplate()
                        .then(function (data) {
                            var numberOfFeedbackItem = data.Result;
                            $scope.feedbackSubjectTemplateList = [];
                            var totalPage = Math.round((numberOfFeedbackItem / sharedScriptManager.cachedData.maxFeedbackSubjectTemplateNumberOnLoad) + 0.5);
                            $scope.feedbackSubjectTemplateTotalPage = totalPage;
                            $scope.isLoadedFeedbackSubjectTemplate = false;
                            for (var i = 1; i <= totalPage; i++) {
                                $scope.getFeedbackSubjectTemplateByPagingIndex(i);
                            }
                        },
                            function () {
                                $scope.isLoadedFeedbackSubjectTemplate = true;
                            });
                };
                $scope.getFeedbackSubjectTemplateByPagingIndex = function (pagingIndex) {
                    feedbackService.getFeedbackSubjectTemplateByPagingIndex({ PagingIndex: pagingIndex })
                        .then(function (data) {
                            var feedbackSubjectTemplate = data.Result;
                            if (feedbackSubjectTemplate !== null && feedbackSubjectTemplate.length > 0) {
                                $scope.feedbackSubjectTemplateList = $scope.feedbackSubjectTemplateList.concat(feedbackSubjectTemplate);
                            }

                            if ($scope.feedbackSubjectTemplateTotalPage === pagingIndex) {
                                $scope.isLoadedFeedbackSubjectTemplate = true;
                                $scope.completedLoadFilterInfo();
                            }
                        },
                            function () {
                                if ($scope.feedbackSubjectTemplateTotalPage === pagingIndex) {
                                    $scope.isLoadedFeedbackSubjectTemplate = true;
                                    $scope.completedLoadFilterInfo();
                                }
                            });
                };
                $scope.completedLoadFilterInfo = function () {
                    if (!$scope.isLoadedFeedbackSubjectTemplate) {
                        return;
                    }

                    $scope.subjectOptions = {
                        NumberOfSuggestItems: 15,
                        SubjectList: $scope.feedbackSubjectTemplateList,
                        Subject: '',
                        IsUpdate: true,
                        OnChangeEvent: $scope.updateSelectedSubject
                    };
                };
                // ---------- End of Subject functions ----------

                // Functions of jHtml.
                $scope.updateDescription = function (description) {
                    $scope.descriptionOptions.SelectedText = description;
                    $scope.feedback.Description = description;
                };
                $scope.updateSolution = function (solution) {
                    $scope.solutionOptions.SelectedText = solution;
                    $scope.feedback.Solution = solution;
                };
                $scope.updateReview = function (review) {
                    $scope.reviewOptions.SelectedText = review;
                    $scope.feedback.Review = review;
                };
                // ---------- End of Functions of jHtml ----------

                $scope.productChangedHandler = function () {
                    $scope.subProductDropdownSettings = {
                        idMember: "Id",
                        nameMember: "Name",
                        sourceData: $scope.getSubProducts($scope.selectedProducts)
                    };
                };

                $scope.subProductChangedHandler = function () {
                    $scope.selectedSubProductIds = [];
                    angular.forEach($scope.selectedSubProducts, function (subProduct) {
                        $scope.selectedSubProductIds.push(subProduct.Id);
                    });

                    $scope.bettypeDropdownSettings = {
                        idMember: "Id",
                        nameMember: "Name",
                        sourceData: $scope.getBettypes($scope.selectedSubProducts)
                    };
                };

                $scope.bettypeChangeHandler = function () {
                    $scope.selectedBettypeIds = [];
                    angular.forEach($scope.selectedBettypes, function (bettype) {
                        $scope.selectedBettypeIds.push(bettype.Id);
                    });
                };

                $scope.categoryChangedHandler = function () {
                    $scope.subCategoryDropdownSettings = {
                        idMember: "Id",
                        nameMember: "Name",
                        sourceData: $scope.getSubCategories($scope.selectedCategories)
                    };

                    if ($scope.feedback) {
                        var currentSubject = $scope.feedback.Subject;
                        var updatedSubject = autoTextScripts.updateSubjectOnSelectedCategories($scope.selectedCategories, currentSubject);
                        if ($scope.categoriesChangedByUser && updatedSubject !== currentSubject) {
                            $scope.feedback.Subject = updatedSubject;
                        }
                    }
                };

                $scope.subCategoryChangedHandler = function () {
                    $scope.selectedSubCategoryIds = [];
                    angular.forEach($scope.selectedSubCategories, function (subCategory) {
                        $scope.selectedSubCategoryIds.push(subCategory.Id);
                    });
                };

                $scope.getSubProducts = function (selectedProducts) {
                    return filterScripts.getSubProducts(
                        selectedProducts,
                        $scope.allSettings.SubProductList,
                        $scope.selectedSubProductIds);
                };

                $scope.getBettypes = function (selectedSubProducts) {
                    return filterScripts.getBettypes(
                        selectedSubProducts,
                        $scope.allSettings.BettypeList,
                        $scope.selectedBettypeIds);
                };

                $scope.getSubCategories = function (selectedCategories) {
                    return filterScripts.getSubCategories(
                        selectedCategories,
                        $scope.allSettings.SubCategoryList,
                        $scope.selectedSubCategoryIds);
                };

                $scope.initController = function () {
                    $uiBlockerService.blockUI();
                    $scope.isSetFocus = true;
                    hotKeyManager.CachedData.ActiveDocumentManager.push({
                        Value: $scope,
                        Id: 'Feedback_UpdateCustomerFeedback'
                    });

                    $scope.getNumberOfFeedbackSubjectTemplate();
                    feedbackService.getSettings()
                        .then(function (data) {
                            $scope.settings = data.Result;
                            $scope.allSettings = data.Result;

                            if (!isShowDeletedStatus) {
                                feedbackService.removeDeletedStatus($scope.settings.StatusList);
                            }

                            feedbackService.getFeedback(feedbackId)
                                .then(function (dataFeedback) {
                                    $scope.feedback = dataFeedback.Result;
                                    $scope.autoGeneratedText = $scope.feedback.AutoField;
                                    $scope.autoGeneratedTextPreview = autoTextScripts.generateTextPreview(
                                        $scope.autoGeneratedText,
                                        $sce.trustAsHtml);

                                    if ($scope.feedback.CustomerInfo.Title.Id === 0) {
                                        $scope.feedback.CustomerInfo.Title = $scope.settings.Titles[0];
                                    }

                                    $scope.feedback.OverrideCRMInfo = false;
                                    oldReview = $scope.feedback.Review;
                                    $scope.panelManager.review = $scope.feedback.IsReviewed;
                                    if ($scope.feedback.ReviewerId > 0) {
                                        $scope.panelManager.showReviewPreview = false;
                                        $scope.reviewedBy = updateFeedbackResources.ReviewedBy
                                            .replace('{0}', $scope.feedback.ReviewerName)
                                            .replace('{1}', $scope.feedback.SolveTimeString);
                                    }

                                    $scope.descriptionOptions = {
                                        OnChangeEvent: $scope.updateDescription,
                                        SelectedText: $scope.feedback.Description,
                                        EditIconText: updateFeedbackResources.InsertEditBlock
                                    };
                                    $scope.solutionOptions = {
                                        OnChangeEvent: $scope.updateSolution,
                                        SelectedText: $scope.feedback.Solution,
                                        EditIconText: updateFeedbackResources.InsertEditBlock
                                    };
                                    $scope.reviewOptions = {
                                        OnChangeEvent: $scope.updateReview,
                                        SelectedText: $scope.feedback.Review,
                                        EditIconText: updateFeedbackResources.InsertEditBlock
                                    };

                                    $scope.communicationDropdownSettings = {
                                        idMember: "Id",
                                        nameMember: "Name",
                                        sourceData: $scope.allSettings.CommunicationToolList
                                    };

                                    $scope.extensionDropdownSettings = {
                                        idMember: "Id",
                                        nameMember: "Value",
                                        sourceData: $scope.allSettings.ExtensionList
                                    };

                                    $scope.categoryDropdownSettings = {
                                        idMember: "Id",
                                        nameMember: "Name",
                                        sourceData: $scope.allSettings.MainCategoryList
                                    };

                                    $scope.subCategoryDropdownSettings = {
                                        idMember: "Id",
                                        nameMember: "Name",
                                        sourceData: $scope.allSettings.SubCategoryList
                                    };

                                    $scope.productDropdownSettings = {
                                        idMember: "Id",
                                        nameMember: "Name",
                                        sourceData: $scope.allSettings.ProductList
                                    };

                                    $scope.subProductDropdownSettings = {
                                        idMember: "Id",
                                        nameMember: "Name",
                                        sourceData: $scope.allSettings.SubProductList
                                    };

                                    $scope.bettypeDropdownSettings = {
                                        idMember: "Id",
                                        nameMember: "Name",
                                        sourceData: $scope.allSettings.BettypeList
                                    };

                                    $scope.updateAllSettingsForFeedback();
                                    $scope.initRelatedCustomer();

                                    $uiBlockerService.unblockUI();
                                }, function () {
                                    $uiBlockerService.unblockUI();
                                });
                        }, function () {
                            $uiBlockerService.unblockUI();
                        });
                };

                $scope.updateAllSettingsForFeedback = function () {
                    $scope.updateSettingCommunication();
                    $scope.updateSettingExtension();
                    $scope.updateSettingCategory();
                    $scope.updateSettingSubCategory();
                    $scope.updateSettingProduct();
                    $scope.updateSettingSubProduct();
                    $scope.updateSettingBettype();

                    SettingManager.updateSettingSelectList($scope.feedback.Language, $scope.settings.Languages);
                    SettingManager.updateSettingSelectList($scope.feedback.Status, $scope.settings.StatusList);
                    SettingManager.updateSettingSelectList($scope.feedback.Role, $scope.settings.Roles);
                    SettingManager.updateSettingSelectList($scope.feedback.Response, $scope.settings.Responses);

                    SettingManager.updateSettingSelectList($scope.feedback.CustomerInfo.Title, $scope.settings.Titles);
                    SettingManager.updateSettingSelectList($scope.feedback.CustomerInfo.LicenseeType, $scope.settings.LicenseeTypes);
                    SettingManager.updateSettingSelectList($scope.feedback.CustomerInfo.SiteSetting, $scope.settings.Sites);
                };

                $scope.updateSettingCommunication = function () {
                    var length = $scope.communicationDropdownSettings.sourceData.length;
                    for (var i = 0; i < length; i++) {
                        var data = $scope.communicationDropdownSettings.sourceData[i];
                        angular.forEach($scope.feedback.Settings, function (setting) {
                            if (setting.SettingType === "Communication" && data.Id === setting.SettingIdLv1) {
                                data.checked = true;
                            }
                        });
                    }
                };

                $scope.updateSettingExtension = function () {
                    var length = $scope.extensionDropdownSettings.sourceData.length;
                    for (var i = 0; i < length; i++) {
                        var data = $scope.extensionDropdownSettings.sourceData[i];
                        angular.forEach($scope.feedback.Settings, function (setting) {
                            if (setting.SettingType === "Station" && data.Id === setting.SettingIdLv1) {
                                data.checked = true;
                            }
                        });
                    }
                };

                $scope.updateSettingCategory = function () {
                    var length = $scope.categoryDropdownSettings.sourceData.length;
                    for (var i = 0; i < length; i++) {
                        var data = $scope.categoryDropdownSettings.sourceData[i];
                        angular.forEach($scope.feedback.Settings, function (setting) {
                            if (setting.SettingType === "Category" && data.Id === setting.SettingIdLv1) {
                                data.checked = true;
                            }
                        });
                    }
                };

                $scope.updateSettingSubCategory = function () {
                    angular.forEach($scope.feedback.Settings, function (setting) {
                        if (setting.SettingType === "Category") {
                            $scope.selectedSubCategoryIds.push(setting.SettingIdLv2);
                        }
                    });
                };

                $scope.updateSettingProduct = function () {
                    var length = $scope.productDropdownSettings.sourceData.length;
                    for (var i = 0; i < length; i++) {
                        var data = $scope.productDropdownSettings.sourceData[i];
                        angular.forEach($scope.feedback.Settings, function (setting) {
                            if (setting.SettingType === "Product" && data.Id === setting.SettingIdLv1) {
                                data.checked = true;
                            }
                        });
                    }
                };

                $scope.updateSettingSubProduct = function () {
                    angular.forEach($scope.feedback.Settings, function (setting) {
                        if (setting.SettingType === "Product") {
                            $scope.selectedSubProductIds.push(setting.SettingIdLv2);
                        }
                    });
                };

                $scope.updateSettingBettype = function () {
                    angular.forEach($scope.feedback.Settings, function (setting) {
                        if (setting.SettingType === "Product") {
                            $scope.selectedBettypeIds.push(setting.SettingIdLv3);
                        }
                    });
                };

                $scope.updateProductSettings = function () {
                    var product = $scope.feedback.Product;
                    SettingManager.updateSettingSelectList(product, $scope.settings.Products);
                    SettingManager.updateInActiveChildSettings($scope.feedback.SubProduct, $scope.settings.Products, product.Id);
                    $scope.subProducts = SettingManager.getChildSettings(product.Id, $scope.settings.Products);
                    SettingManager.updateInActiveChildSettings($scope.feedback.BetType, $scope.subProducts, $scope.feedback.SubProduct.Id);
                };

                $scope.updateSelectedSite = function () {
                    $scope.feedback.CustomerInfo.SiteSetting = $scope.feedback.CustomerInfo.SiteSetting || { Id: 0 };
                };

                $scope.productChanged = function () {
                    $scope.subProducts = SettingManager.getChildSettings($scope.feedback.Product.Id, $scope.settings.Products);
                    $scope.feedback.SubProduct = $scope.subProducts[0];
                    $scope.subProductChanged();
                };

                $scope.subProductChanged = function () {
                    var childSettings = SettingManager.getChildSettings($scope.feedback.SubProduct.Id, $scope.subProducts);
                    if (!childSettings || childSettings.length === 0) {
                        var notApplySetting = $scope.subProducts[0];
                        childSettings = [{ Id: notApplySetting.Id, Name: notApplySetting.Name }];
                    }

                    $scope.bettypes = childSettings;

                    if ($scope.bettypes.length === 0) {
                        $scope.errorMessage(updateFeedbackResources.NoBettypeError.replace('{0}', '[' + $scope.feedback.Product.Value + ']'));
                    }
                    else {
                        $scope.hideMessage();
                        $scope.feedback.BetType = $scope.bettypes[0];
                    }
                };

                $scope.validateFeedback = function () {
                    $scope.hideMessage();

                    var feedback = $scope.feedback;
                    var feedbackTime = new Date(feedback.FeedbackTimeString);
                    var resolutionTime = new Date(feedback.ResolutionTimeString);
                    if (feedbackTime > resolutionTime) {
                        $scope.errorMessage(updateFeedbackResources.ErrorFeedbackResolutionTime);
                        return false;
                    }

                    if ($scope.selectedCommunications.length === 0) {
                        $scope.errorMessage(updateFeedbackResources.NACommmunicationTool);
                        return false;
                    }

                    if (feedback.Language === $scope.settings.Languages[0]) {
                        $scope.errorMessage(updateFeedbackResources.NALanguage);
                        return false;
                    }

                    if (feedback.HasRelated && $scope.customersInput !== '') {
                        $scope.errorMessage(updateFeedbackResources.CustomerVerification);
                        return false;
                    }

                    $scope.GetCategoryParams();
                    if ($scope.feedback.Categories.length === 0) {
                        $scope.errorMessage(updateFeedbackResources.Error_NA_MainSubCategory);
                        return false;
                    }

                    var inValidCategories = filterScripts.CheckCategoryParams(
                        $scope.selectedCategories,
                        $scope.selectedSubCategories,
                        $scope.allSettings.SubCategoryList);
                    if (inValidCategories.length !== 0) {
                        $scope.errorMessage(sharedScriptManager.stringFormat(updateFeedbackResources.InvalidCategoryError, [inValidCategories.join(", ")]));
                        return false;
                    }

                    $scope.requiredManager.subject = feedback.Subject.trim().length !== 0;
                    if (!$scope.requiredManager.subject) {
                        $scope.errorMessage(updateFeedbackResources.EmptySubject);
                        return false;
                    }

                    $scope.requiredManager.description = feedback.Description.trim().length !== 0 && feedback.Description !== '<br>';
                    if (!$scope.requiredManager.description) {
                        $scope.errorMessage(updateFeedbackResources.EmptyRemark);
                        return false;
                    }

                    if (($scope.autoGeneratedText.length + feedback.Description.length) > crmConstants.MaxDescLength) {
                        $scope.errorMessage(updateFeedbackResources.DescriptionMaxLengthError);
                        return false;
                    }

                    $scope.requiredManager.solution = feedback.Solution.trim().length !== 0 && feedback.Solution !== '<br>';
                    if (!$scope.requiredManager.solution) {
                        $scope.errorMessage(updateFeedbackResources.EmptySolution);
                        return false;
                    }

                    if (feedback.Solution.length > crmConstants.MaxDescLength) {
                        $scope.errorMessage(updateFeedbackResources.SolutionMaxLengthError);
                        return false;
                    }

                    $scope.requiredManager.review = !(feedback.IsReviewed && (feedback.Review.trim().length === 0 || feedback.Review === '<br>'));
                    if (!$scope.requiredManager.review) {
                        $scope.errorMessage(updateFeedbackResources.EmptyReview);
                        return false;
                    }

                    return true;
                };

                $scope.updateFeedback = function () {
                    if (!$scope.validateFeedback()) {
                        return;
                    }

                    parent.dialogManager.confirm(updateFeedbackResources.Confirm_Changes, updateFeedbackResources.Confirm_Changes_Message,
                        function () {
                            var feedback = $scope.feedback;
                            if (!feedback.OverrideCRMInfo) {
                                $scope.updateCustomerFeedback(feedback);
                                return;
                            }

                            parent.homeManager.showConfirmOverrideCRMInfo(updateFeedbackResources.ConfirmOverrideCRMInfo, function (bool) {
                                if (bool) { $scope.updateCustomerFeedback(feedback); }
                            });
                        }
                    );
                };

                $scope.GetCommunicationParams = function () {
                    $scope.feedback.CommunicationIds = filterScripts.GetCommunicationParams($scope.selectedCommunications);
                };

                $scope.GetExtensionParams = function () {
                    $scope.feedback.ExtensionIds = filterScripts.GetExtensionParams($scope.selectedExtensions, $scope.allSettings.ExtensionNA);
                };

                $scope.GetProductParams = function () {
                    $scope.feedback.Products = filterScripts.GetProductParams(
                        {
                            selectedProducts: $scope.selectedProducts,
                            selectedSubProducts: $scope.selectedSubProducts,
                            selectedBettypes: $scope.selectedBettypes
                        },
                        {
                            ProductNA: $scope.allSettings.ProductNA,
                            SubProductNA: $scope.allSettings.SubProductNA,
                            BettypeNA: $scope.allSettings.BettypeNA
                        },
                        $scope.allSettings.BettypeList);
                };

                $scope.GetCategoryParams = function () {
                    $scope.feedback.Categories = filterScripts.GetCategoryParams(
                        $scope.selectedCategories,
                        $scope.selectedSubCategories,
                        $scope.allSettings.SubCategoryList);
                };

                $scope.updateCustomerFeedback = function (feedback) {
                    $uiBlockerService.blockUI();
                    $scope.GetCommunicationParams();
                    $scope.GetExtensionParams();
                    $scope.GetProductParams();
                    $scope.GetCategoryParams();

                    if ($scope.feedback.HasRelated && $scope.relatedCustomerResultDirective.relatedCustomers) {
                        feedback.RelatedCustomers = $scope.relatedCustomerResultDirective.relatedCustomers.filter(function (value) {
                            return value.Id !== 0;
                        });
                    }
                    else {
                        feedback.RelatedCustomers = null;
                    }

                    feedback.UpdateReviewMode = !$scope.hasReviewPermission ? 0 : (!feedback.IsReviewed ? 2 : (oldReview === feedback.Review ? 0 : 1));
                    //$scope.assignIdForParam(feedback);

                    feedback.AutoField = $scope.autoGeneratedText;

                    feedbackService.updateFeedback(feedback, isDeletedFeedbackView)
                        .then(function (data) {
                            var result = data.Result;
                            if (result && result.Code === 0) {
                                alertBoxService.show({
                                    type: crmConstants.Enums.MessageType.Success,
                                    message: updateFeedbackResources.UpdateFeedbackSuccessfully,
                                    callback: function () {
                                        parent.ClosePopup();
                                        if (feedback.OverrideCRMInfo) {
                                            parent.leftPanelManager.loadLeftPanel(feedback.CustomerInfo.Name, true);
                                        }
                                    }
                                });
                            }
                            else {
                                $scope.errorMessage(result.Code ? result.Message : 'Oppss... An error occurred while processing your request.');
                            }

                            $uiBlockerService.unblockUI();
                        }, function () {
                            $uiBlockerService.unblockUI();
                        });
                };

                $scope.assignIdForParam = function (feedback) {
                    feedback.Product = { Id: feedback.Product.Id };
                    feedback.SubProduct = { Id: feedback.SubProduct.Id };
                };

                $scope.errorMessage = function (error) {
                    alertBoxService.show({
                        type: crmConstants.Enums.MessageType.Error,
                        message: error
                    });
                };

                $scope.hideMessage = function () {
                    alertBoxService.hide();
                };

                $scope.invokeHotKey_CtrlS = function () {
                    $scope.updateFeedback();
                };

                $scope.invokeHotKey_CtrlE = function () {
                    if (!$scope.feedback.HasRelated) {
                        return;
                    }

                    $scope.relatedCustomerResultDirective.verifyUsernames($scope.customersInput);
                };

                $scope.initRelatedCustomer = function () {
                    if ($scope.feedback.HasRelated) {
                        $scope.relatedCustomerResultDirective.loadRelatedCustomers($scope.feedback.RelatedCustomers);
                    }
                };

                $scope.verifyRelatedCustomer = function () {
                    var customerString = $scope.relatedCustomerResultDirective.normalizeUsername($scope.customersInput);

                    if ($scope.relatedCustomerResultDirective.isValidUsername(customerString)) {
                        $scope.hideMessage();
                        $scope.relatedCustomerResultDirective.verifyUsernames(customerString);
                    }
                    else {
                        $scope.errorMessage(updateFeedbackResources.CustomerNameLengthErrorMessage);
                    }
                };

                $scope.showHideDescriptionPreview = function () {
                    $scope.panelManager.showDescriptionPreview = !$scope.panelManager.showDescriptionPreview;
                    $scope.autoGeneratedTextPreview = autoTextScripts.generateTextPreview(
                        $scope.autoGeneratedText,
                        $sce.trustAsHtml);
                };

                $scope.updateRemarkPrefix = function () {
                    if (!$scope.feedback || (!$scope.relatedCustomerResultDirective.verifyUsernamesAtLeastOneTime && !$scope.CustomerCheckboxChanged)) {
                        return;
                    }

                    var prefix = autoTextScripts.updatePrefixForCusomter(
                        $scope.feedback.HasRelated,
                        $scope.relatedCustomerResultDirective.relatedCustomers,
                        $scope.autoGeneratedText,
                        $sce.trustAsHtml);
                    $scope.autoGeneratedText = prefix.autoGeneratedText;
                    $scope.autoGeneratedTextPreview = prefix.previewText;
                };

                $scope.relatedCustomersChanged = function () {
                    $scope.updateRemarkPrefix();
                };

                $scope.IsRelatedCustomerCheckboxChanged = function () {
                    $scope.CustomerCheckboxChanged = true;
                    $scope.updateRemarkPrefix();
                };

                angular.element(document).ready(function () {
                    sharedScriptManager.safeApply($scope);
                    $scope.initController();
                });
            }]);
})();