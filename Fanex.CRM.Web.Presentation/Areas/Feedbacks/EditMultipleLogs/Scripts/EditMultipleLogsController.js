        $scope.validateEditMultipleLogsCriteria = function (criteria) {
            var result = true;
            var feedbackTime = new Date(criteria.StartTime);
            var resolutionTime = new Date(criteria.EndTime);

            if (feedbackTime > resolutionTime) {
                $scope.resultMessage = viewResources.Multiple_Logs_ErrorEndTime;
                result = false;
            }

            if (result && $scope.selectedCommunications.length == 0) {
                $scope.resultMessage = viewResources.Multiple_Logs_NACommmunicationTool;
                result = false;
            }

            if (result && criteria.LanguageId === crmConstants.Enums.Language.NotApply) {
                $scope.resultMessage = viewResources.Multiple_Logs_NALanguage;
                result = false;
            }

            if (result && criteria.Categories.length == 0) {
                $scope.resultMessage = viewResources.Error_NA_MainSubCategory;
                result = false;
            }

            $scope.requiredManager.subject = !(criteria.Subject === '');
            if (result && !$scope.requiredManager.subject) {
                $scope.resultMessage = viewResources.Multiple_Logs_EmptySubject;
                result = false;
            }

            $scope.requiredManager.remark = !($.trim(criteria.Remark) === '' || criteria.Remark === '<br>');
            if (result && !$scope.requiredManager.remark) {
                $scope.resultMessage = viewResources.Multiple_Logs_EmptyRemark;
                result = false;
            }

            $scope.requiredManager.solution = !($.trim(criteria.Solution) === '' || criteria.Solution === '<br>');
            if (result && !$scope.requiredManager.solution) {
                $scope.resultMessage = viewResources.Multiple_Logs_EmptySolution;
                result = false;
            }

            $scope.requiredManager.review = !(criteria.IsReviewed && ($.trim(criteria.Review) === '' || criteria.Review === '<br>'));
            if (result && !$scope.requiredManager.review) {
                $scope.resultMessage = viewResources.Multiple_Logs_EmptyReview;
                result = false;
            }

            if (result) {
                $scope.isShowResultMessage = false;
            } else {
                $scope.isShowResultMessage = true;
                $scope.isSuccess = false;
            }

            return result;
        };
