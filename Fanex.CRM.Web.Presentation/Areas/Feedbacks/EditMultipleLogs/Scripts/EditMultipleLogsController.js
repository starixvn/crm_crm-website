(function () {
    "use strict";
    /* global sharedScriptManager,
    moment,
    crmConstants,
    viewResources,
    hotKeyManager,
    hasReviewPermission,
    currentTime*/
    /* jshint camelcase: false */
    angular.module('edit-multiple-logs-application').controller('editMultipleLogsController', ['$scope', '$editMultipleLogsService',
        function ($scope, $editMultipleLogsService) {
            $scope.multipleLogs = multipleLogs;
            $scope.multipleLogs.NoInquiries = $scope.multipleLogs.NoInquiries === 0 ? null : $scope.multipleLogs.NoInquiries;

            $scope.oldmultipleLogs = angular.copy(multipleLogs);
            $scope.extensionList = null;
            $scope.countryList = null;
            $scope.provinceList = null;
            $scope.communicationToolList = null;
            $scope.languageList = null;
            $scope.mainCategoryList = null;
            $scope.subCategoryList = null;
            $scope.betTypeList = null;
            $scope.statusList = null;
            $scope.siteList = null;
            $scope.roleList = null;
            $scope.responseList = null;
            $scope.feedbackSubjectTemplateList = [];
            $scope.feedbackSubjectTemplateTotalPage = 0;
            $scope.isLoadedFeedbackSubjectTemplate = false;
            $scope.lastRemarkPrefix = '';
            $scope.isSuccess = false;
            $scope.isShowResultMessage = false;
            $scope.resultMessage = '';
            $scope.licenseeTypes = [];
            $scope.hasReviewPermission = hasReviewPermission;
            $scope.autoGeneratedText = $scope.multipleLogs.AutoField;
            $scope.selectedSubProductIds = [];
            $scope.selectedBettypeIds = [];
            $scope.selectedSubCategoryIds = [];
            $scope.isCN88 = isCN88;

            $scope.listOfCustomers = '';
            $scope.feedbackList = '';
            $scope.TextSettings = {
                Filter: "Search",
                NoItemChecked: "N/A",
                CheckAll: "All"
            };

            $scope.requiredManager = {
                subject: true,
                remark: true,
                solution: true,
                review: true
            };

            $scope.selectAllField = false;
            $scope.selectFields = {
                isUpdateStartTime: false,
                isUpdateExtension: false,
                isUpdateEndTime: false,
                isUpdateResponse: false,
                isUpdateCommunication: false,
                isUpdateLanguage: false,
                isUpdateCategory: false,
                isUpdateProduct: false,
                isUpdateStatus: false,
                isUpdateRole: false,
                isUpdateSite: false,
                isUpdateCountry: false,
                isUpdateLicenseeType: false,
                isUpdateProvince: false,
                isUpdateSubject: false,
                isUpdateAutoField: false,
                isUpdateSolution: false,
                isUpdateReviewed: false,
                isUpdateNoInquiries: false
            };

            $scope.onSelectAllField = function () {
                var fields = Object.keys($scope.selectFields);
                for (var i = 0; i < fields.length; i++) {
                    $scope.selectFields[fields[i]] = $scope.selectAllField;
                }
            };

            $scope.onSelectField = function (field) {
                if (!$scope.selectFields[field]) {
                    $scope.selectAllField = false;
                }
            };

            $scope.initController = function () {
                $scope.getSettings();
                $scope.getNumberOfFeedbackSubjectTemplate();
            };

            $scope.getNumberOfFeedbackSubjectTemplate = function () {
                $scope.BlockUI();
                $editMultipleLogsService.getNumberOfFeedbackSubjectTemplate()
                    .then(function (data) {
                        var numberOfFeedbackItem = data.Result;
                        $scope.feedbackSubjectTemplateList = [];
                        var totalPage = Math.round((numberOfFeedbackItem / sharedScriptManager.cachedData.maxFeedbackSubjectTemplateNumberOnLoad) + 0.5);
                        $scope.feedbackSubjectTemplateTotalPage = totalPage;
                        $scope.isLoadedFeedbackSubjectTemplate = false;
                        for (var i = 1; i <= totalPage; i++) {
                            $scope.getFeedbackSubjectTemplateByPagingIndex(i);
                        }
                    }, function () {
                        $scope.isLoadedFeedbackSubjectTemplate = true;
                    });
            };
            $scope.getFeedbackSubjectTemplateByPagingIndex = function (pagingIndex) {
                $scope.BlockUI();
                $editMultipleLogsService.getFeedbackSubjectTemplateByPagingIndex({ PagingIndex: pagingIndex })
                    .then(function (data) {
                        var feedbackSubjectTemplate = data.Result;
                        if (feedbackSubjectTemplate !== null && feedbackSubjectTemplate.length > 0) {
                            $scope.feedbackSubjectTemplateList = $scope.feedbackSubjectTemplateList.concat(feedbackSubjectTemplate);
                        }

                        if ($scope.feedbackSubjectTemplateTotalPage === pagingIndex) {
                            $scope.isLoadedFeedbackSubjectTemplate = true;
                            $scope.unblockUI();
                        }
                    }, function () {
                        if ($scope.feedbackSubjectTemplateTotalPage === pagingIndex) {
                            $scope.isLoadedFeedbackSubjectTemplate = true;
                            $scope.unblockUI();
                        }
                    });
            };
            $scope.initSelectedLogInfo = function () {
                $scope.listOfCustomers = $scope.getListOfCustomers(parent.homeManager.CachedData.feedbacks);
                $scope.feedbackList = $scope.getFeedbackIdList(parent.homeManager.CachedData.feedbacks);
                parent.homeManager.CachedData.feedbacks = null;
            };

            $scope.getListOfCustomers = function (feedbacks) {
                var customerList = [];
                angular.forEach(feedbacks, function (feedback) {
                    this.push(feedback.UserName);
                }, customerList);

                return customerList.join(', ');
            };
            $scope.getFeedbackIdList = function (feedbacks) {
                var feedbackIds = [];
                angular.forEach(feedbacks, function (feedback) {
                    this.push(feedback.FeedbackId);
                }, feedbackIds);

                return feedbackIds;
            };

            /* jshint camelcase: false */
            $scope.invokeHotKey_CtrlS = function () {
                $scope.editMultipleLogs();
                $scope.$apply();
            };
            /* jshint camelcase: false */
            $scope.updateStartTime = function (selectedTime) {
                $scope.multipleLogs.StartTime = selectedTime;
                if (new Date($scope.multipleLogs.EndTime) <= selectedTime) {
                    $scope.multipleLogs.EndTime = new Date(selectedTime);
                    $scope.multipleLogs.EndTime.setMinutes(selectedTime.getMinutes() + 1);
                }
            };
            $scope.updateEndTime = function (selectedTime) {
                $scope.multipleLogs.EndTime = selectedTime;
                if (selectedTime <= new Date($scope.multipleLogs.StartTime)) {
                    $scope.multipleLogs.StartTime = new Date(selectedTime);
                    $scope.multipleLogs.StartTime.setMinutes(selectedTime.getMinutes() - 1);
                }
            };

            $scope.updateSelectedSubject = function (subject) {
                $scope.multipleLogs.Subject = subject;
            };
            $scope.updateRemark = function (remark) {
                $scope.multipleLogs.Remark = remark;
            };
            $scope.updateSolution = function (solution) {
                $scope.multipleLogs.Solution = solution;
            };
            $scope.updateReview = function (review) {
                $scope.multipleLogs.Review = review;
            };
            $scope.updateSelectedLicenseeType = function (licenseeType) {
                $scope.multipleLogs.LicenseeType = licenseeType;
                $scope.safeApply();
            };

            $scope.GetCommunicationParams = function () {
                return filterScripts.GetCommunicationParams($scope.selectedCommunications);
            };

            $scope.GetExtensionParams = function () {
                return filterScripts.GetExtensionParams(
                    $scope.selectedExtensions,
                    $scope.allSettings.ExtensionNA);
            };

            $scope.GetProductParams = function () {
                return filterScripts.GetProductParams(
                    {
                        selectedProducts: $scope.selectedProducts,
                        selectedSubProducts: $scope.selectedSubProducts,
                        selectedBettypes: $scope.selectedBettypes
                    },
                    {
                        ProductNA: $scope.allSettings.ProductNA,
                        SubProductNA: $scope.allSettings.SubProductNA,
                        BettypeNA: $scope.allSettings.BettypeNA
                    },
                    $scope.allSettings.BettypeList);
            };

            $scope.GetCategoryParams = function () {
                return filterScripts.GetCategoryParams(
                    $scope.selectedCategories,
                    $scope.selectedSubCategories,
                    $scope.allSettings.SubCategoryList);
            };

            $scope.editMultipleLogs = function () {
                var fields = Object.keys($scope.selectFields);
                var isSelectedField = false;
                for (var i = 0; i < fields.length; i++) {
                    if ($scope.selectFields[fields[i]]) {
                        isSelectedField = true;
                        break;
                    }
                }

                if (!isSelectedField) {
                    $scope.resultMessage = viewResources.NoFieldSelectedMessage;
                    $scope.isShowResultMessage = true;
                    return;
                }

                $scope.isShowResultMessage = false;
                $scope.isSuccess = true;
                var isResetReview = $scope.oldmultipleLogs.IsReviewed && !$scope.multipleLogs.IsReviewed;
                var isReviewNotChanged = !$scope.oldmultipleLogs.IsReviewed && !$scope.multipleLogs.IsReviewed;
                var updateReviewedMode = (!$scope.hasReviewPermission || isReviewNotChanged) ? crmConstants.Enums.UpdateReviewedMode.NotChange :
                    (isResetReview ? crmConstants.Enums.UpdateReviewedMode.Reset : crmConstants.Enums.UpdateReviewedMode.Change);

                var editCriteria = {
                    CommunicationIds: $scope.GetCommunicationParams(),
                    ExtensionIds: $scope.GetExtensionParams(),
                    Products: $scope.GetProductParams(),
                    Categories: $scope.GetCategoryParams(),
                    ListFeedbackId: $scope.feedbackList.join(','),
                    StartTime: moment(new Date($scope.multipleLogs.StartTime)).format(crmConstants.Enums.FormatConstant.MM_DD_YYYY_HH_MM_TT_String_Moment),
                    EndTime: moment(new Date($scope.multipleLogs.EndTime)).format(crmConstants.Enums.FormatConstant.MM_DD_YYYY_HH_MM_TT_String_Moment),
                    CountryId: $scope.multipleLogs.Country.Id,
                    ProvinceId: $scope.multipleLogs.Province.Id,
                    LanguageId: $scope.multipleLogs.Language.Id,
                    StatusId: $scope.multipleLogs.Status.Id,
                    RoleId: $scope.multipleLogs.RoleInfo.Id,
                    SiteId: $scope.selectedSite ? $scope.selectedSite.Id : crmConstants.Enums.Site.NotApply,
                    LicenseeTypeId: $scope.multipleLogs.LicenseeType.Id,
                    ResponseId: $scope.multipleLogs.Response.Id,
                    Subject: $scope.multipleLogs.Subject,
                    Remark: $scope.multipleLogs.Remark,
                    Solution: $scope.multipleLogs.Solution,
                    IsReviewed: $scope.multipleLogs.IsReviewed,
                    Review: $scope.multipleLogs.Review,
                    UpdateReviewedMode: updateReviewedMode,
                    AutoField: $scope.autoGeneratedText,
                    NoInquiries: $scope.multipleLogs.NoInquiries
                };
                if ($scope.validateEditMultipleLogsCriteria(editCriteria)) {
                    parent.dialogManager.confirm(viewResources.ConfirmMultipleUpdates, viewResources.ConfirmMultipleUpdatesMessage,
                        function () {
                            $scope.BlockUI();
                            for (var i = 0; i < fields.length; i++) {
                                editCriteria[fields[i]] = $scope.selectFields[fields[i]];
                            }

                            $editMultipleLogsService.editMultipleLogs(editCriteria)
                                .then(function (data) {
                                    $scope.showResult(data.Result);
                                    $scope.unblockUI();
                                }, function () {
                                    $scope.unblockUI();
                                });
                        }
                    );
                }
            };
            $scope.showResult = function (result) {
                $scope.resultMessage = result.Message;
                $scope.isShowResultMessage = true;
                $scope.unblockUI();

                if (result.Code !== 0) {
                    $scope.isSuccess = false;
                    return;
                }

                parent.homeManager.CachedData.shareInfoBetweenPopup = result;
                parent.homeManager.CachedData.shouldReloadView = true;

                setTimeout(function () {
                    parent.ClosePopup();
                }, sharedScriptManager.cachedData.alertSuccessTime);
            };
            $scope.updateChangeFlag = function () {
                if ($scope.isParamsChange()) {
                    parent.homeManager.CachedData.isChangingDataPopUp = true;
                    parent.homeManager.CachedData.ignoreConfirmMessage = viewResources.Confirm_Ignore_MultipleLogs_Changes;
                } else {
                    parent.homeManager.CachedData.isChangingDataPopUp = false;
                }

                $scope.safeApply();
            };
            $scope.isParamsChange = function () {
                return $scope.multipleLogs.Country.Id !== $scope.oldmultipleLogs.Country.Id ||
                    $scope.multipleLogs.Province.Id !== $scope.oldmultipleLogs.Province.Id ||
                    $scope.multipleLogs.Language.Id !== $scope.oldmultipleLogs.Language.Id ||
                    $scope.multipleLogs.Status.Id !== $scope.oldmultipleLogs.Status.Id ||
                    $scope.multipleLogs.RoleInfo.Id !== $scope.oldmultipleLogs.RoleInfo.Id ||
                    $scope.multipleLogs.SiteInfo.Id !== $scope.oldmultipleLogs.SiteInfo.Id ||
                    $scope.multipleLogs.LicenseeType.Id !== $scope.oldmultipleLogs.LicenseeType.Id ||
                    $scope.multipleLogs.Response.Id !== $scope.oldmultipleLogs.Response.Id ||
                    $scope.multipleLogs.Remark !== $scope.oldmultipleLogs.Remark ||
                    $scope.multipleLogs.Solution !== $scope.oldmultipleLogs.Solution ||
                    $scope.multipleLogs.Subject !== $scope.oldmultipleLogs.Subject;
            };
            $scope.validateEditMultipleLogsCriteria = function (criteria) {
                var result = true;

                if (result && $scope.selectFields.isUpdateCommunication && $scope.selectedCommunications.length === 0) {
                    $scope.resultMessage = viewResources.Multiple_Logs_NACommmunicationTool;
                    result = false;
                }

                if (result && $scope.selectFields.isUpdateLanguage && parseInt(criteria.LanguageId, 10) === crmConstants.Enums.Language.NotApply) {
                    $scope.resultMessage = viewResources.Multiple_Logs_NALanguage;
                    result = false;
                }

                if (result && $scope.selectFields.isUpdateCategory && criteria.Categories.length === 0) {
                    $scope.resultMessage = viewResources.Error_NA_MainSubCategory;
                    result = false;
                }

                var inValidCategories = filterScripts.CheckCategoryParams(
                    $scope.selectedCategories,
                    $scope.selectedSubCategories,
                    $scope.allSettings.SubCategoryList);
                if (result && $scope.selectFields.isUpdateCategory && inValidCategories.length !== 0) {
                    $scope.resultMessage = sharedScriptManager.stringFormat(viewResources.InvalidCategoryError, [inValidCategories.join(", ")]);
                    result = false;
                }

                $scope.requiredManager.subject = !(criteria.Subject === '');
                if (result && $scope.selectFields.isUpdateSubject && !$scope.requiredManager.subject) {
                    $scope.resultMessage = viewResources.Multiple_Logs_EmptySubject;
                    result = false;
                }

                $scope.requiredManager.remark = !($.trim(criteria.Remark) === '' || criteria.Remark === '<br>');
                if (result && $scope.selectFields.isUpdateAutoField && !$scope.requiredManager.remark) {
                    $scope.resultMessage = viewResources.Multiple_Logs_EmptyRemark;
                    result = false;
                }

                if (result && $scope.autoGeneratedText.length + criteria.Remark.length > crmConstants.MaxDescLength) {
                    $scope.resultMessage = viewResources.DescriptionMaxLengthError;
                    result = false;
                }

                $scope.requiredManager.solution = !($.trim(criteria.Solution) === '' || criteria.Solution === '<br>');
                if (result && $scope.selectFields.isUpdateSolution && !$scope.requiredManager.solution) {
                    $scope.resultMessage = viewResources.Multiple_Logs_EmptySolution;
                    result = false;
                }

                if (criteria.Solution.length > crmConstants.MaxDescLength) {
                    $scope.resultMessage = viewResources.SolutionMaxLengthError;
                    result = false;
                }

                $scope.requiredManager.review = !(criteria.IsReviewed && ($.trim(criteria.Review) === '' || criteria.Review === '<br>'));
                if (result && $scope.selectFields.isUpdateReviewed && !$scope.requiredManager.review) {
                    $scope.resultMessage = viewResources.Multiple_Logs_EmptyReview;
                    result = false;
                }

                if (result) {
                    $scope.isShowResultMessage = false;
                } else {
                    $scope.isShowResultMessage = true;
                    $scope.isSuccess = false;
                }

                return result;
            };
            $scope.unblockUI = function () {
                parent.$.unblockUI();

                hotKeyManager.CachedData.isBlockingUI = false;
            };
            $scope.BlockUI = function () {
                hotKeyManager.CachedData.isBlockingUI = true;
                parent.BlockUI();
            };

            $scope.productChangedHandler = function () {
                $scope.subProductDropdownSettings = {
                    idMember: "Id",
                    nameMember: "Name",
                    sourceData: $scope.getSubProducts($scope.selectedProducts)
                };
            };

            $scope.subProductChangedHandler = function () {
                $scope.selectedSubProductIds = [];
                angular.forEach($scope.selectedSubProducts, function (subProduct) {
                    $scope.selectedSubProductIds.push(subProduct.Id);
                });

                $scope.bettypeDropdownSettings = {
                    idMember: "Id",
                    nameMember: "Name",
                    sourceData: $scope.getBettypes($scope.selectedSubProducts)
                };
            };

            $scope.bettypeChangeHandler = function () {
                $scope.selectedBettypeIds = [];
                angular.forEach($scope.selectedBettypes, function (bettype) {
                    $scope.selectedBettypeIds.push(bettype.Id);
                });
            };

            $scope.categoryChangedHandler = function () {
                $scope.subCategoryDropdownSettings = {
                    idMember: "Id",
                    nameMember: "Name",
                    sourceData: $scope.getSubCategories($scope.selectedCategories)
                };

                if ($scope.multipleLogs) {
                    var currentSubject = $scope.multipleLogs.Subject;
                    var updatedSubject = autoTextScripts.updateSubjectOnSelectedCategories($scope.selectedCategories, currentSubject);
                    if ($scope.categoriesChangedByUser && updatedSubject !== currentSubject) {
                        $scope.multipleLogs.Subject = updatedSubject;
                    }
                }
            };

            $scope.subCategoryChangedHandler = function () {
                $scope.selectedSubCategoryIds = [];
                angular.forEach($scope.selectedSubCategories, function (subCategory) {
                    $scope.selectedSubCategoryIds.push(subCategory.Id);
                });
            };

            $scope.getSubProducts = function (selectedProducts) {
                return filterScripts.getSubProducts(
                    selectedProducts,
                    $scope.allSettings.SubProductList,
                    $scope.selectedSubProductIds);
            };

            $scope.getBettypes = function (selectedSubProducts) {
                return filterScripts.getBettypes(
                    selectedSubProducts,
                    $scope.allSettings.BettypeList,
                    $scope.selectedBettypeIds);
            };

            $scope.getSubCategories = function (selectedCategories) {
                return filterScripts.getSubCategories(
                    selectedCategories,
                    $scope.allSettings.SubCategoryList,
                    $scope.selectedSubCategoryIds);
            };

            $scope.getSettings = function () {
                $scope.BlockUI();
                $scope.isLoadedAllSite = false;
                $editMultipleLogsService.getSettings()
                    .then(function (data) {
                        var allSetting = data.Result;
                        $scope.allSettings = data.Result;

                        $scope.countryList = allSetting.CountryList !== null ? allSetting.CountryList : [];
                        $scope.countryList.unshift({
                            Id: crmConstants.Enums.Country.NotApply,
                            Name: viewResources.Symbol_NotApply
                        });

                        $scope.provinceList = allSetting.ProvinceList;

                        $scope.languageList = allSetting.LanguageList !== null ? allSetting.LanguageList : [];
                        $scope.languageList.unshift({
                            Id: crmConstants.Enums.Language.NotApply,
                            Name: viewResources.Symbol_NotApply
                        });

                        $scope.statusList = allSetting.StatusList;
                        $scope.siteList = allSetting.SiteList;
                        $scope.roleList = allSetting.RoleList;
                        $scope.responseList = allSetting.ResponseList;
                        $scope.licenseeTypes = allSetting.LicenseeType;
                        $scope.licenseeTypeOptions = {
                            DataList: allSetting.LicenseeType,
                            OnChangeEvent: $scope.updateSelectedLicenseeType,
                            SelectedId: $scope.multipleLogs.LicenseeType.Id
                        };

                        $scope.selectedSite = $scope.multipleLogs.SiteInfo;
                        $scope.siteDropdownSettings = {
                            idMember: "Id",
                            nameMember: "Name",
                            sourceData: allSetting.SiteList,
                            childrenMember: "ChildSites"
                        };

                        $scope.communicationDropdownSettings = {
                            idMember: "Id",
                            nameMember: "Name",
                            sourceData: $scope.allSettings.CommunicationToolList
                        };

                        $scope.extensionDropdownSettings = {
                            idMember: "Id",
                            nameMember: "Value",
                            sourceData: $scope.allSettings.ExtensionList
                        };

                        $scope.categoryDropdownSettings = {
                            idMember: "Id",
                            nameMember: "Name",
                            sourceData: $scope.allSettings.MainCategoryList
                        };

                        $scope.subCategoryDropdownSettings = {
                            idMember: "Id",
                            nameMember: "Name",
                            sourceData: $scope.allSettings.SubCategoryList
                        };

                        $scope.productDropdownSettings = {
                            idMember: "Id",
                            nameMember: "Name",
                            sourceData: $scope.allSettings.ProductList
                        };

                        $scope.subProductDropdownSettings = {
                            idMember: "Id",
                            nameMember: "Name",
                            sourceData: $scope.allSettings.SubProductList
                        };

                        $scope.bettypeDropdownSettings = {
                            idMember: "Id",
                            nameMember: "Name",
                            sourceData: $scope.allSettings.BettypeList
                        };

                        $scope.updateAllSettingsForLog();
                        $scope.completedLoadFilterInfo();
                    },
                        function () {
                            $scope.completedLoadFilterInfo();
                        });
            };
            $scope.completedLoadFilterInfo = function () {
                $scope.initSelectedLogInfo();
                $scope.unblockUI();
            };
            $scope.updateAllSettingsForLog = function () {
                //$scope.updateProductSettings();
                $scope.updateSettingCommunication();
                $scope.updateSettingExtension();
                $scope.updateSettingCategory();
                $scope.updateSettingSubCategory();
                $scope.updateSettingProduct();
                $scope.updateSettingSubProduct();
                $scope.updateSettingBettype();

                SettingManager.updateSettingSelectList($scope.multipleLogs.Language, $scope.languageList);
                SettingManager.updateSettingSelectList($scope.multipleLogs.Status, $scope.statusList);
                SettingManager.updateSettingSelectList($scope.multipleLogs.RoleInfo, $scope.roleList);
                SettingManager.updateSettingSelectList($scope.multipleLogs.Response, $scope.responseList);

                !$scope.isCN88 && SettingManager.updateSettingSelectList($scope.multipleLogs.SiteInfo, $scope.siteList);
                SettingManager.updateSettingSelectList($scope.multipleLogs.LicenseeType, $scope.licenseeTypeOptions.DataList);
            };

            $scope.updateSettingCommunication = function () {
                var length = $scope.communicationDropdownSettings.sourceData.length;
                for (var i = 0; i < length; i++) {
                    var data = $scope.communicationDropdownSettings.sourceData[i];
                    angular.forEach($scope.multipleLogs.Settings, function (setting) {
                        if (setting.SettingType === "Communication" && data.Id === setting.SettingIdLv1) {
                            data.checked = true;
                        }
                    });
                }
            };

            $scope.updateSettingExtension = function () {
                var length = $scope.extensionDropdownSettings.sourceData.length;
                for (var i = 0; i < length; i++) {
                    var data = $scope.extensionDropdownSettings.sourceData[i];
                    angular.forEach($scope.multipleLogs.Settings, function (setting) {
                        if (setting.SettingType === "Station" && data.Id === setting.SettingIdLv1) {
                            data.checked = true;
                        }
                    });
                }
            };

            $scope.updateSettingCategory = function () {
                var length = $scope.categoryDropdownSettings.sourceData.length;
                for (var i = 0; i < length; i++) {
                    var data = $scope.categoryDropdownSettings.sourceData[i];
                    angular.forEach($scope.multipleLogs.Settings, function (setting) {
                        if (setting.SettingType === "Category" && data.Id === setting.SettingIdLv1) {
                            data.checked = true;
                        }
                    });
                }
            };

            $scope.updateSettingSubCategory = function () {
                angular.forEach($scope.multipleLogs.Settings, function (setting) {
                    if (setting.SettingType === "Category") {
                        $scope.selectedSubCategoryIds.push(setting.SettingIdLv2);
                    }
                });
            };

            $scope.updateSettingProduct = function () {
                var length = $scope.productDropdownSettings.sourceData.length;
                for (var i = 0; i < length; i++) {
                    var data = $scope.productDropdownSettings.sourceData[i];
                    angular.forEach($scope.multipleLogs.Settings, function (setting) {
                        if (setting.SettingType === "Product" && data.Id === setting.SettingIdLv1) {
                            data.checked = true;
                        }
                    });
                }
            };

            $scope.updateSettingSubProduct = function () {
                angular.forEach($scope.multipleLogs.Settings, function (setting) {
                    if (setting.SettingType === "Product") {
                        $scope.selectedSubProductIds.push(setting.SettingIdLv2);
                    }
                });
            };

            $scope.updateSettingBettype = function () {
                angular.forEach($scope.multipleLogs.Settings, function (setting) {
                    if (setting.SettingType === "Product") {
                        $scope.selectedBettypeIds.push(setting.SettingIdLv3);
                    }
                });
            };

            $scope.updateProductSettings = function () {
                var product = $scope.multipleLogs.Product;
                var productList = $scope.productOptions.DataList;
                SettingManager.updateSettingSelectList(product, productList);

                var subProduct = $scope.multipleLogs.SubProduct;
                var subProductList = $scope.subProductOptions.DataList;
                SettingManager.updateInActiveChildSettings(subProduct, productList, product.Id);
                subProductList = SettingManager.getChildSettings(product.Id, productList);
                SettingManager.updateInActiveChildSettings($scope.multipleLogs.BetType, subProductList, subProduct.Id);
            };
            $scope.getReviewedInfo = function () {
                return sharedScriptManager.stringFormat(
                    viewResources.ReviewedInformation,
                    [$scope.multipleLogs.Reviewer, $scope.multipleLogs.ReviewedTimeString]);
            };

            angular.element(document).ready(function () {
                sharedScriptManager.safeApply($scope);
                $scope.$watch(function ($scope) {
                    $scope.updateChangeFlag();
                });

                parent.homeManager.CachedData.shareInfoBetweenPopup.PopupController = $scope;

                registerOptions($scope);
                $scope.initController();
                hotKeyManager.CachedData.ActiveDocumentManager.push({
                    Value: $scope,
                    Id: "MultipleLogs_Edit"
                });

                hotKeyManager.CachedData.isBubbleToParent = false;
            });
        }]);
})();