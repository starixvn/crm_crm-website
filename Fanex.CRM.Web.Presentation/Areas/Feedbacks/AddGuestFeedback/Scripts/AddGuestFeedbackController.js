(function () {
    "use strict";
    /* global 
    MessageResult,
    registerOptions,
    registerUpdateFunctions,
    registerHotkeyFunctions,
    crmConstants,
    sharedScriptManager,
    viewResources,
    moment,
    dialogManager*/
    /* jshint camelcase: false */
    window.MessageResult = function (message, isShowMessage, isSuccess) {
        this.Message = message;
        this.IsShowMessage = isShowMessage;
        this.IsSuccess = isSuccess;
    };

    angular.module('feedbacks-addguestfeedback-application').controller('addGuestFeedbackController',
    ['$scope', '$uiBlockerService', 'addGuestFeedbackService', '$sce',
    function ($scope, $uiBlockerService, addGuestFeedbackService, $sce) {
        $scope.customerInfo = {
            Name: '',
            Title: {
                Id: 0
            },
            Passport: {
                Name: ''
            },
            PersonalInfoContacts: [{ Name: '', Phone: '' }, { Name: '', Phone: '' }, { Name: '', Phone: '' }, { Name: '', Phone: ''}],
            BettingCode: ["", ""],
            PhoneInfo: [{
                CountryCode: "",
                AreaCode: "",
                PhoneNumber: ""
            }, {
                CountryCode: "",
                AreaCode: "",
                PhoneNumber: ""
            }, {
                CountryCode: "",
                AreaCode: "",
                PhoneNumber: ""
            }, {
                CountryCode: "",
                AreaCode: "",
                PhoneNumber: ""
            }],
            MobilePhone: {
                CountryCode: "",
                AreaCode: "",
                PhoneNumber: ""
            },
            FaxInfo: {
                CountryCode: "",
                AreaCode: "",
                FaxNumber: ""
            }
        };

        $scope.customersInput = '';

        $scope.isShowCustomerDetailBox = true;
        $scope.isShowFeedbackDetailBox = true;
        $scope.isShowDescriptionBox = true;
        $scope.isShowSolutionBox = true;
        $scope.isShowDescriptionPreview = false;
        $scope.isShowSolutionPreview = false;
        $scope.feedbackSubjectTemplateList = [];
        $scope.feedbackSubjectTemplateTotalPage = 0;
        $scope.isLoadedFeedbackSubjectTemplate = false;
        $scope.isLoadedAllSettings = false;
        $scope.isLoading = true;
        $scope.allSettings = null;
        $scope.autoGeneratedText = '';
        $scope.TextSettings = {
            Filter: "Search",
            NoItemChecked: "N/A",
            CheckAll: "All"
        };
        
        $scope.addGuestFeedbackParams = {
            OverrideCRMInfo: false,
            Subject: null,
            StartTime: null,
            EndTime: null,
            Description: '',
            Solution: '',
            HasRelated: false,
            CustomerInfo: $scope.customerInfo,
            Language: {
                Id: 0
            },
            Country: {
                Id: 0
            }
        };
        $scope.oldParams = null;
        $scope.initController = function () {
            sharedScriptManager.safeApply($scope);
            $scope.initDefaultOption();
            $scope.getNumberOfFeedbackSubjectTemplate();
            $scope.getAllSetting();
        };
        $scope.getAllSetting = function () {
            $uiBlockerService.blockUI();
            var params = {};
            addGuestFeedbackService.getAllSetting(params)
                .then(function (data) {
                    $scope.isLoadedAllSettings = true;
                    $scope.allSettings = data.Result;
                    $scope.completedLoadFilterInfo();
                },
                function () {
                    $scope.isLoadedAllSettings = true;
                    $scope.completedLoadFilterInfo();
                });
        };

        $scope.productChangedHandler = function () {
            $scope.subProductDropdownSettings = {
                idMember: "Id",
                nameMember: "Name",
                sourceData: $scope.getSubProducts($scope.selectedProducts),
                childrenMember: "ChildSettings",
            };
        }

        $scope.subProductChangedHandler = function () {
            $scope.bettypeDropdownSettings = {
                idMember: "Id",
                nameMember: "Name",
                sourceData: $scope.getBettypes($scope.selectedSubProducts, $scope.allSettings.ProductList),
                childrenMember: "ChildSettings",
            };
        }

        $scope.getSubProducts = function (seletedProducts) {
            var cloneSeletedProducts = [];
            if (seletedProducts) {
                cloneSeletedProducts = angular.copy(seletedProducts);
            }

            var productsWithSubProducts = [];
            angular.forEach(cloneSeletedProducts, function (product) {
                // only get product having subproducts
                if (product.ChildSettings.length != 0) {
                    angular.forEach(product.ChildSettings, function (subProducts) {
                        subProducts.ChildSettings = [];
                    })
                    productsWithSubProducts.push(product);
                }
            });

            return productsWithSubProducts;
        }

        $scope.getBettypes = function (seletedSubProducts, allProducts) {
            var selectedProductIds = [];
            angular.forEach(seletedSubProducts, function (selectedSubProduct) {
                if (selectedProductIds.indexOf(selectedSubProduct.ParentId) < 0) {
                    selectedProductIds.push(selectedSubProduct.ParentId);
                }
            });

            var selectProductandSubProductIds = [];
            angular.forEach(selectedProductIds, function (productId) {
                var Ids = {
                    ProductId: productId,
                    SubProductIds: []
                };

                angular.forEach(seletedSubProducts, function (selectedSubProduct) {
                    if (selectedSubProduct.ParentId == productId) {
                        Ids.SubProductIds.push(selectedSubProduct.Id);
                    }
                });

                selectProductandSubProductIds.push(Ids);
            })

            var selectedProducts = [];
            angular.forEach(selectProductandSubProductIds, function (ids) {
                angular.forEach(allProducts, function (product) {
                    if (product.Id == ids.ProductId) {
                        var subProducts = [];
                        angular.forEach(product.ChildSettings, function (subProduct) {
                            // only get subproduct having bettypes
                            if (ids.SubProductIds.indexOf(subProduct.Id) >= 0 && subProduct.ChildSettings.length > 0) {
                                subProducts.push(angular.copy(subProduct));
                            }
                        });
                        
                        // only get product having subproducts
                        if (subProducts.length > 0) {
                            var p = angular.copy(product);
                            p.ChildSettings = subProducts;
                            selectedProducts.push(p)
                        }
                    }
                })
            });

            return selectedProducts;
        }

        $scope.completedLoadFilterInfo = function () {
            if (!$scope.isLoadedAllSettings ||
                !$scope.isLoadedFeedbackSubjectTemplate) {
                return;
            }

            $scope.birthdayOptions.IsRerenderPicker = true;
            $scope.titleOptions.DataList = $scope.allSettings.TitleList;
            $scope.communicationToolOptions.DataList = $scope.allSettings.CommunicationToolList;
            $scope.productOptions.DataList = $scope.allSettings.ProductList;
            $scope.responseOptions.DataList = $scope.allSettings.ResponseList;
            $scope.languageOptions.DataList = $scope.allSettings.LanguageList;
            $scope.mainCategoryOptions.DataList = $scope.allSettings.MainCategoryList;
            $scope.betTypeOptions.DataList = $scope.allSettings.ProductList[0].ChildSettings;
            $scope.statusOptions.DataList = $scope.allSettings.StatusList;

            $scope.extensionOptions.DataList = $scope.allSettings.ExtensionList;
            $scope.subCategoryOptions.DataList = $scope.allSettings.MainCategoryList[0].ChildSettings;
            $scope.countryOptions.DataList = $scope.allSettings.CountryList;

            $scope.subjectOptions = {
                NumberOfSuggestItems: 15,
                SubjectList: $scope.feedbackSubjectTemplateList,
                Subject: '',
                IsUpdate: true,
                OnChangeEvent: $scope.updateSelectedSubject
            };

            $scope.communicationDropdownSettings = {
                idMember: "Id",
                nameMember: "Name",
                sourceData: $scope.allSettings.CommunicationToolList
            };

            $scope.extensionDropdownSettings = {
                idMember: "Id",
                nameMember: "Value",
                sourceData: $scope.allSettings.ExtensionList
            };

            $scope.categoryDropdownSettings = {
                idMember: "Id",
                nameMember: "Name",
                sourceData: $scope.allSettings.MainCategoryList,
                childrenMember: "ChildSettings"
            };

            $scope.productDropdownSettings = {
                idMember: "Id",
                nameMember: "Name",
                sourceData: $scope.allSettings.ProductList
            };

            $scope.subProductDropdownSettings = {
                idMember: "Id",
                nameMember: "Name",
                sourceData: $scope.getSubProducts($scope.selectedProducts),
                childrenMember: "ChildSettings",
            };

            $scope.bettypeDropdownSettings = {
                idMember: "Id",
                nameMember: "Name",
                sourceData: $scope.getBettypes($scope.selectedSubProducts, $scope.allSettings.ProductList),
                childrenMember: "ChildSettings",
            };

            $scope.descriptionOptions.SelectedText = '';
            $scope.solutionOptions.SelectedText = '';

            $scope.updateSelectedCommunicationTool($scope.communicationToolOptions.DataList[0]);

            
            $scope.updateSelectedResponse($scope.responseOptions.DataList[0]);

            $scope.updateSelectedStatus($scope.statusOptions.DataList[0]);
            $scope.addGuestFeedbackParams.CustomerInfo = $scope.customerInfo;
            $scope.initRemarkPrefix();
            $scope.customerInfo.Title = $scope.allSettings.TitleList[0];
            $scope.customerInfo.LicenseeType = $scope.allSettings.LicenseeType[0];

            $scope.oldParams = angular.copy($scope.addGuestFeedbackParams);
            $scope.updateChangeFlag();
            $scope.isLoading = false;
            $uiBlockerService.unblockUI();
        };
        $scope.getNumberOfFeedbackSubjectTemplate = function () {
            $uiBlockerService.blockUI();
            addGuestFeedbackService.getNumberOfFeedbackSubjectTemplate()
            .then(function (data) {
                var numberOfFeedbackItem = data.Result;
                $scope.feedbackSubjectTemplateList = [];
                var totalPage = Math.round((numberOfFeedbackItem / sharedScriptManager.cachedData.maxFeedbackSubjectTemplateNumberOnLoad) + 0.5);
                $scope.feedbackSubjectTemplateTotalPage = totalPage;
                $scope.isLoadedFeedbackSubjectTemplate = false;
                for (var i = 1; i <= totalPage; i++) {
                    $scope.getFeedbackSubjectTemplateByPagingIndex(i);
                }
            },
            function () {
                $scope.isLoadedFeedbackSubjectTemplate = true;
            });
        };
        $scope.getFeedbackSubjectTemplateByPagingIndex = function (pagingIndex) {
            $uiBlockerService.blockUI();
            addGuestFeedbackService.getFeedbackSubjectTemplateByPagingIndex({ PagingIndex: pagingIndex })
            .then(function (data) {
                var feedbackSubjectTemplate = data.Result;
                if (feedbackSubjectTemplate != null && feedbackSubjectTemplate.length > 0) {
                    $scope.feedbackSubjectTemplateList = $scope.feedbackSubjectTemplateList.concat(feedbackSubjectTemplate);
                }

                if ($scope.feedbackSubjectTemplateTotalPage === pagingIndex) {
                    $scope.isLoadedFeedbackSubjectTemplate = true;
                    $scope.completedLoadFilterInfo();
                }
            },
            function () {
                if ($scope.feedbackSubjectTemplateTotalPage === pagingIndex) {
                    $scope.isLoadedFeedbackSubjectTemplate = true;
                    $scope.completedLoadFilterInfo();
                }
            });
        };

        $scope.showHideCustomerDetailBox = function () {
            $scope.isShowCustomerDetailBox = !$scope.isShowCustomerDetailBox;
        };
        $scope.showHideFeedbackDetailBox = function () {
            $scope.isShowFeedbackDetailBox = !$scope.isShowFeedbackDetailBox;
        };
        $scope.showDescriptionPreview = function () {            
            $scope.isShowDescriptionPreview = true;
            $scope.autoGeneratedTextPreview = $scope.getTextPreview();
        };
        $scope.showDescriptionEditor = function () {
            $scope.isShowDescriptionPreview = false;
        };
        $scope.showSolutionPreview = function () {
            $scope.isShowSolutionPreview = true;
        };
        $scope.showSolutionEditor = function () {
            $scope.isShowSolutionPreview = false;
        };
        // ---------- End of Functions of Related customers ----------

        $scope.GetCommunicationParams = function () {
            var communicationIds = [];
            angular.forEach($scope.selectedCommunications, function (communication) {
                communicationIds.push(communication.Id);
            })
            $scope.addGuestFeedbackParams.CommunicationIds = communicationIds.join(",");
        }

        $scope.GetExtensionParams = function () {
            var extensionIds = [];
            angular.forEach($scope.selectedExtensions, function (extension) {
                extensionIds.push(extension.Id);
            })

            if (extensionIds.length == 0) {
                extensionIds = [$scope.allSettings.ExtensionNA.Id];
            }
            $scope.addGuestFeedbackParams.ExtensionIds = extensionIds.join(",");
        }

        $scope.GetProductParams = function () {
            var products = [];
            angular.forEach($scope.selectedProducts, function (product) {
                var subIds = [];
                angular.forEach($scope.selectedSubProducts, function (subProduct) {
                    if (subProduct.ParentId == product.Id) {
                        subIds.push(subProduct.Id);
                    }
                })

                if (subIds.length == 0) {
                    products.push({
                        ProductId: product.Id,
                        SubProductId: "",
                        BettypeIds: []
                    })
                }
                else {
                    angular.forEach(subIds, function (subId) {
                        products.push({
                            ProductId: product.Id,
                            SubProductId: subId,
                            BettypeIds: []
                        })
                    })
                }
            })

            angular.forEach(products, function (p) {
                angular.forEach($scope.selectedBettypes, function (bettype) {
                    if (p.ProductId == bettype.GrandParentId && p.SubProductId == bettype.ParentId) {
                        p.BettypeIds.push(bettype.Id);
                    }
                })

                if (p.SubProductId == "") {
                    p.SubProductId = $scope.allSettings.SubProductNA.Id;
                }

                if (p.BettypeIds.length == 0) {
                    p.BettypeIds = [$scope.allSettings.BettypeNA.Id];
                }

                p.BettypeIds = p.BettypeIds.join(",");
            })

            if (products.length == 0) {
                products = [
                    {
                        ProductId: $scope.allSettings.ProductNA.Id,
                        SubProductId: $scope.allSettings.SubProductNA.Id,
                        BettypeIds: $scope.allSettings.BettypeNA.Id
                    }
                ];
            }

            $scope.addGuestFeedbackParams.Products = products;
        }

        $scope.GetCategoryParams = function () {
            var categories = [];
            angular.forEach($scope.selectedCategories, function (category) {
                if (category.ParentId != 0) {
                    categories.push({
                        MainCategoryID: category.ParentId,
                        SubCategoryID: category.Id
                    })
                }
                else {
                    categories.push({
                        MainCategoryID: category.Id,
                        SubCategoryID: ''
                    })
                }
            })
            $scope.addGuestFeedbackParams.Categories = categories;
        }

        $scope.CheckInvalidCategories = function () {
            var invalidCategories = [];
            angular.forEach($scope.selectedCategories, function (category) {
                if (category.ParentId == 0) {
                    invalidCategories.push(category.Name);
                }
            })

            return invalidCategories.join(",")
        }

        $scope.addFeedback = function () {
            $uiBlockerService.blockUI();
            $scope.GetCommunicationParams();
            $scope.GetExtensionParams();
            $scope.GetProductParams();
            $scope.GetCategoryParams();

            $scope.addGuestFeedbackParams.RelatedCustomerId = $scope.relatedCustomerResultDirective.getRelatedCustomerId();
            $scope.addGuestFeedbackParams.AutoField = $scope.autoGeneratedText;
            var params = angular.copy($scope.addGuestFeedbackParams);
            params.CustomerInfo = $scope.customerInfo;
            params.StartTime = sharedScriptManager.formatTimeToSendToServer($scope.addGuestFeedbackParams.StartTime);
            params.EndTime = sharedScriptManager.formatTimeToSendToServer($scope.addGuestFeedbackParams.EndTime);
            if (!$scope.validateAddParams(params)) {
                $uiBlockerService.unblockUI();
                return;
            }            

            if (!isNameValid(params.CustomerInfo.Name)) {
                params.CustomerInfo.Name = updateName(params.CustomerInfo.Name);
                var message = "Content will be saved without special characters such as <, >, &, #";
                $uiBlockerService.unblockUI();
                parent.dialogManager.alert("Warning", message, "OK", function () {
                    callAddGuestFeedback(params);
                });
            }
            else {
                callAddGuestFeedback(params);
            }

           
        };

        var callAddGuestFeedback = function (params) {
            addGuestFeedbackService.addFeedback(params)
                .then(function (data) {
                    var addResult = data.Result;
                    $scope.showAddResult(addResult);
                },
                function () {
                    $uiBlockerService.unblockUI();
                });
        }

        var specialChars = ["<", ">", "#", "&"];

        var isNameValid = function (name) {
            for (var i = 0; i < specialChars.length; i++) {
                if (name.indexOf(specialChars[i]) >= 0) {
                    return false;
                }
            }
            
            return true;
        }

        var updateName = function (name) {
            for (var i = 0; i < specialChars.length; i++) {
                name = name.replace(specialChars[i], "");
            }

            return name;
        }

        $scope.validateAddParams = function (params) {
            var result = true;
            var message = '';

            var feedbackTime = new Date(params.StartTime);
            var resolutionTime = new Date(params.EndTime);
            if (feedbackTime > resolutionTime) {
                message = viewResources.ErrorFeedbackResolutionTime;
                result = false;
            }

            if (result && $.trim(params.CustomerInfo.Name) === '') {
                message = viewResources.Error_EmptyId;
                result = false;
            }

            if (result && params.CommunicationIds == "") {
                message = viewResources.Error_NACommmunicationTool;
                result = false;
            }

            if (result && params.Categories.length == 0) {
                message = viewResources.Error_NAMainCategory;
                result = false;
            }

            var invalidCategories = $scope.CheckInvalidCategories();
            if (result && invalidCategories != "") {
                message = viewResources.NoSubcategoryError.replace('{0}', '[' + invalidCategories + ']');
                result = false;
            }

            if (result && params.Language.Id === crmConstants.Enums.Language.NotApply) {
                message = viewResources.Error_NALanguage;
                result = false;
            }

            if (result && params.Subject === null || params.Subject === '') {
                message = viewResources.Error_EmptySubject;
                result = false;
            }

            if (result &&
                ($.trim(params.Description) === '' || params.Description === '<br>')) {
                message = viewResources.Error_EmptyRemark;
                result = false;
            }

            if (result &&
                ($.trim(params.Solution) === '' || params.Solution === '<br>')) {
                message = viewResources.Error_EmptySolution;
                result = false;
            }

            if (result && params.HasRelated && $scope.customersInput !== '') {
                message = viewResources.Error_VerifyRelatedCustomer;
                result = false;
            }

            $scope.messageResultOptions = new MessageResult(message, !result, result);
            return result;
        };
        $scope.showAddResult = function (addResult) {
            $scope.oldParams = angular.copy($scope.addGuestFeedbackParams);
            $scope.updateChangeFlag();
            if (addResult.Code !== 0) {
                $scope.messageResultOptions = new MessageResult(addResult.Message, true, false);
                $uiBlockerService.unblockUI();
                return;
            }

            if (addResult.Code === 0) {
                $scope.messageResultOptions = new MessageResult(addResult.Message, true, true);
                setTimeout(function () {
                    $scope.messageResultOptions = new MessageResult('', false, false);
                    $scope.safeApply();

                    parent.leftPanelManager.DOMElements.checkboxIsGuest.attr('checked', true);
                    parent.leftPanelManager.loadLeftPanel($scope.customerInfo.Name, true);
                }, sharedScriptManager.cachedData.alertSuccessTime);

                $uiBlockerService.unblockUI();
                return;
            }

            $uiBlockerService.unblockUI();
        };
        $scope.setFocus = function () {
            $scope.isSetFocus = true;
            $scope.safeApply();
        };
        $scope.updateChangeFlag = function () {
            if ($scope.isParamsChange()) {
                parent.homeManager.CachedData.isChangingData = true;
                parent.homeManager.CachedData.ignoreConfirmMessage = viewResources.Confirm_Ignore_Feedback_AddGuestFeedback;
            } else {
                parent.homeManager.CachedData.isChangingData = false;
            }

            $scope.safeApply();
        };
        $scope.isParamsChange = function () {
            return !($scope.oldParams &&
                $scope.addGuestFeedbackParams &&
                $scope.oldParams.CustomerInfo &&
                $scope.oldParams.CustomerInfo.Title.Id === $scope.addGuestFeedbackParams.CustomerInfo.Title.Id &&
                $scope.oldParams.CustomerInfo.FirstName === $scope.addGuestFeedbackParams.CustomerInfo.FirstName &&
                $scope.oldParams.CustomerInfo.LastName === $scope.addGuestFeedbackParams.CustomerInfo.LastName &&
                sharedScriptManager.deepCompare($scope.oldParams.CustomerInfo.PhoneInfo, $scope.addGuestFeedbackParams.CustomerInfo.PhoneInfo) &&
                sharedScriptManager.deepCompare($scope.oldParams.CustomerInfo.FaxInfo, $scope.addGuestFeedbackParams.CustomerInfo.FaxInfo) &&
                sharedScriptManager.deepCompare($scope.oldParams.CustomerInfo.MobilePhone, $scope.addGuestFeedbackParams.CustomerInfo.MobilePhone) &&
                sharedScriptManager.deepCompare($scope.oldParams.CustomerInfo.PersonalInfoContacts,
                    $scope.addGuestFeedbackParams.CustomerInfo.PersonalInfoContacts) &&
                $scope.oldParams.CustomerInfo.Skype === $scope.addGuestFeedbackParams.CustomerInfo.Skype &&
                $scope.oldParams.CustomerInfo.Email === $scope.addGuestFeedbackParams.CustomerInfo.Email &&
                $scope.oldParams.CustomerInfo.MSN === $scope.addGuestFeedbackParams.CustomerInfo.MSN &&

                $scope.oldParams.CustomerInfo.Passport.Name === $scope.addGuestFeedbackParams.CustomerInfo.Passport.Name &&
                $scope.oldParams.CustomerInfo.BirthDayString === $scope.addGuestFeedbackParams.CustomerInfo.BirthDayString &&
                sharedScriptManager.deepCompare($scope.oldParams.CustomerInfo.BettingCode, $scope.addGuestFeedbackParams.CustomerInfo.BettingCode) &&
                $scope.oldParams.CustomerInfo.IsVIP === $scope.addGuestFeedbackParams.CustomerInfo.IsVIP &&

                $scope.oldParams.CommunicationTool.Id === $scope.addGuestFeedbackParams.CommunicationTool.Id &&
                $scope.oldParams.Language.Id === $scope.addGuestFeedbackParams.Language.Id &&
                $scope.oldParams.Response.Id === $scope.addGuestFeedbackParams.Response.Id &&
                $scope.oldParams.Status.Id === $scope.addGuestFeedbackParams.Status.Id &&
                $scope.oldParams.Country.Id === $scope.addGuestFeedbackParams.Country.Id &&
                $scope.oldParams.RelatedCustomerId === $scope.addGuestFeedbackParams.RelatedCustomerId &&
                $scope.oldParams.Description === $scope.addGuestFeedbackParams.Description &&
                $scope.oldParams.Solution === $scope.addGuestFeedbackParams.Solution);
        };

        $scope.getTextPreview = function () {
            var previewText = $scope.autoGeneratedText.replace(/\n/g, "<br>");
            if (previewText && previewText != "<br>") {
                previewText = previewText + "<br><br>";
            }
            return $sce.trustAsHtml(previewText);
        }
        
        $scope.initRemarkPrefix = function () {
            if (!$scope.addGuestFeedbackParams.StartTime) {
                return;
            }

            $scope.autoGeneratedText = $scope.generateTimeAndToolPrefix() + " \n" + $scope.generateCustomerPrefix();
            $scope.autoGeneratedTextPreview = $scope.getTextPreview();
        }

        $scope.updateTimeAndToolPrefix = function () {
            if (!$scope.addGuestFeedbackParams.StartTime) {
                return;
            }

            var newTimeAndToolPrefix = $scope.generateTimeAndToolPrefix();
            var oldTimeAndToolPrefix = $scope.matchTimeAndToolPrefix();
            if (oldTimeAndToolPrefix != '') {
                $scope.autoGeneratedText = $scope.autoGeneratedText.replace(oldTimeAndToolPrefix, newTimeAndToolPrefix);
            }
            else {
                $scope.autoGeneratedText = newTimeAndToolPrefix + "\n" + $scope.autoGeneratedText;
            }
            $scope.autoGeneratedTextPreview = $scope.getTextPreview();
        }

        $scope.matchTimeAndToolPrefix = function () {
            var pattern = "Date Time & Tool: \\d{8}\\/\\d{2}:\\d{2}\\D{2}\\/";
            for (var i = 0; i < $scope.communicationToolOptions.DataList.length; i++) {
                var tool = $scope.communicationToolOptions.DataList[i];
                var match = $scope.autoGeneratedText.match(new RegExp(pattern + tool.Name));
                if (match != null) {
                    return match[0];
                }
            }
            
            return '';
        }

        $scope.updateCusomterPrefix = function () {
            if (!$scope.addGuestFeedbackParams.StartTime) {
                return;
            }

            var customerPrefix = $scope.generateCustomerPrefix();
            $scope.autoGeneratedText = ($scope.autoGeneratedText.indexOf("System ID:") >= 0) ?
                $scope.autoGeneratedText = $scope.autoGeneratedText.replace(/System ID:.*/, customerPrefix) :
                $scope.autoGeneratedText = $scope.autoGeneratedText + "\n" + customerPrefix;
            $scope.autoGeneratedTextPreview = $scope.getTextPreview();
        }

        $scope.generateTimeAndToolPrefix = function () {
            return sharedScriptManager.stringFormat("Date Time & Tool: {0}/{1}",
            [moment($scope.addGuestFeedbackParams.StartTime).format(crmConstants.Enums.FormatConstant.StartTime_RemarkPrefix),
                $scope.addGuestFeedbackParams.CommunicationTool.Name]);
        }

        $scope.generateCustomerPrefix = function () {
            var customerArr = [];
            if ($scope.addGuestFeedbackParams.HasRelated) {
                angular.forEach($scope.relatedCustomerResultDirective.relatedCustomers, function (customer, index) {
                    if (customer.Id != 0) {
                        customerArr.push(customer.Name);
                    }
                });
            }

            return "System ID: " + customerArr.join(", ");
        }

        $scope.onStartTimeChanged = function () {
            $scope.$apply(function () {
                $scope.updateTimeAndToolPrefix();
            });
        };

        $scope.relatedCustomersChanged = function () {
            $scope.updateCusomterPrefix();
        }

        $scope.IsRelatedCustomerCheckboxChanged = function () {
            $scope.updateCusomterPrefix();
        }

        $scope.verifyRelatedCustomer = function () {
            var customerString = $scope.relatedCustomerResultDirective.normalizeUsername($scope.customersInput);

            if ($scope.relatedCustomerResultDirective.isValidUsername(customerString)) {
                $scope.messageResultOptions = new MessageResult('', false, false);
                $scope.relatedCustomerResultDirective.verifyUsernames(customerString);
            }
            else {
                $scope.messageResultOptions = new MessageResult(viewResources.CustomerNameLengthErrorMessage, true, false);
            }
        };

        angular.element(document).ready(function () {
            registerOptions($scope);
            registerUpdateFunctions($scope);
            registerHotkeyFunctions($scope);

            $scope.$watch(function ($scope) {
                $scope.updateChangeFlag();
            });

            $scope.initController();
            $scope.setFocus();
            $scope.registerHotKey();
        });
    } ]);
})();
