           ((!$scope.oldCommunicationLog.IsReviewed && !$scope.communicationLog.IsReviewed) ||
            ($scope.oldCommunicationLog.IsReviewed && $scope.communicationLog.IsReviewed)) &&
            ($scope.oldCommunicationLog.Review === $scope.communicationLog.Review);
